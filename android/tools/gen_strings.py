def esc(v):
    v = sx.escape(v)
    v = v.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    # A bare % (not a %1$s style argument) must be doubled.
    import re
    v = re.sub(r"%(?!\d+\$[sd])", "%%", v)
    return v

